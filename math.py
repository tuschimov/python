# Math modülü
import math
# from math import  floor, ceil, sqrt

# floor(): Sayıyı kendisine en yakın "küçük" tam sayıya yuvarlar.abs
print(math.floor(7.645)) # Output: 7
# ceil(): Sayıyı kendisine en yakın "büyük" tam sayıya yuvarlar.
print(math.ceil(-7.645)) # Output: 8
# sqrt(): Karekök alma
print(math.sqrt(64)) # Mutlaka float verir.
# pow(): Üs alma
print(math.pow(2,3))
# log(): Logaritma alır. --> math.log(x,base)
print(math.log(234))